"""Export the new interface's contracts for the front end.

Writes apps/play-web/src/contracts/schema.json (JSON Schema of every model in
frx.play_models.EXPORTED) and then apps/play-web/src/contracts/types.ts through
json-schema-to-typescript. The output is deterministic: running it twice changes nothing.

usage: uv run python tools/play_schema.py [--check]
  --check  only report whether the committed files are up to date (exit 1 if not)
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

from frx import play_models
from frx.domain import ROOT
from pydantic import TypeAdapter

OUT = ROOT / "apps/play-web/src/contracts"


def name_of(item) -> str:
    if isinstance(item, type):
        return item.__name__
    for name in dir(play_models):
        if getattr(play_models, name) is item:
            return name
    raise ValueError(f"unnamed export {item!r}")


def tidy(schema, root=True):
    """Drop per-field titles and null defaults, which would otherwise become stray type names."""
    if isinstance(schema, dict):
        out = {}
        for key, value in schema.items():
            if key == "title" and not root:
                continue
            if key == "default" and value is None:
                continue
            out[key] = tidy(value, root=False) if key != "properties" else {
                name: tidy(sub, root=False) for name, sub in value.items()
            }
        return out
    if isinstance(schema, list):
        return [tidy(item, root=False) for item in schema]
    return schema


def build_schema() -> dict:
    adapters = [
        (name_of(item), "serialization", TypeAdapter(item)) for item in play_models.EXPORTED
    ]
    mapping, top = TypeAdapter.json_schemas(adapters, ref_template="#/definitions/{model}")
    definitions = dict(top.get("$defs", {}))
    for (name, _), schema in mapping.items():
        if "$ref" not in schema:
            definitions[name] = schema  # an annotated union such as Block or TurnEvent
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "FrxContracts",
        "description": "Generated by tools/play_schema.py from apps/api/frx/play_models.py.",
        "type": "object",
        "additionalProperties": False,
        "properties": {name: {"$ref": f"#/definitions/{name}"} for name, _, _ in adapters},
        "definitions": {name: tidy(definitions[name]) for name in sorted(definitions)},
    }


def render_types(schema_path: Path) -> str:
    script = ROOT / "apps/play-web/tools/schema-to-ts.mjs"
    done = subprocess.run(
        ["node", str(script), str(schema_path)], capture_output=True, text=True, check=True
    )
    return done.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    schema_text = json.dumps(build_schema(), ensure_ascii=False, indent=2, sort_keys=False) + "\n"
    schema_file = OUT / "schema.json"
    types_file = OUT / "types.ts"
    if check:
        if not schema_file.exists() or schema_file.read_text() != schema_text:
            print("schema.json is out of date; run uv run python tools/play_schema.py")
            return 1
        if not types_file.exists() or types_file.read_text() != render_types(schema_file):
            print("types.ts is out of date; run uv run python tools/play_schema.py")
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    schema_file.write_text(schema_text)
    types_file.write_text(render_types(schema_file))
    print(f"wrote {schema_file.relative_to(ROOT)} and {types_file.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
